// Bundles PDF.js + page-flip + the reader engine into ONE offline HTML string
// at src/reader-engine/readerHtml.generated.ts
//
//   npm install --prefix reader-web     (once)
//   npm run build:reader                (after editing reader-web/engine.*)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const web = join(root, 'reader-web');
const mods = join(web, 'node_modules');
const read = (p, enc = 'utf8') => readFileSync(p, enc);

// Hermes stores a string as UTF-16 if it contains ANY non-ASCII character, doubling its size
// in the app bundle. All non-ASCII characters in these sources sit inside string literals or
// comments, where a \uXXXX escape means exactly the same thing.
const asciiJs = (code) =>
  code.replace(/[^\x00-\x7f]/g, (c) => {
    if (c.codePointAt(0) > 0xffff) throw new Error('astral character in JS source');
    return '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0');
  });

const pdfjsPkg = JSON.parse(read(join(mods, 'pdfjs-dist/package.json')));

const src = {
  pdfjs: asciiJs(read(join(mods, 'pdfjs-dist/legacy/build/pdf.min.mjs'))),
  worker: asciiJs(read(join(mods, 'pdfjs-dist/legacy/build/pdf.worker.min.mjs'))),
  pageflip: asciiJs(read(join(mods, 'page-flip/dist/js/page-flip.browser.js'))),
  wasm: Object.fromEntries(
    ['jbig2.wasm', 'openjpeg.wasm', 'qcms_bg.wasm'].map((f) => [f, readFileSync(join(mods, 'pdfjs-dist/wasm', f)).toString('base64')]),
  ),
};

// JSON is valid JS; escaping "<" keeps "</script>" / "<!--" from ever appearing in the page.
const srcScript = 'window.__PAGETURN_SRC = ' + JSON.stringify(src).replace(/</g, '\\u003c') + ';';
const engine = asciiJs(read(join(web, 'engine.js')));
if (/<\/script|<!--/i.test(engine)) throw new Error('engine.js must not contain "</script" or "<!--"');

const html = read(join(web, 'template.html'))
  .replace('/*__CSS__*/', () => read(join(web, 'engine.css')))
  .replace('/*__SRC__*/', () => srcScript)
  .replace('/*__ENGINE__*/', () => engine);

if (/[^\x00-\x7f]/.test(html)) throw new Error('reader HTML is not pure ASCII');

const outFile = join(root, 'src/reader-engine/readerHtml.generated.ts');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/build-reader.mjs — do not edit by hand.\n` +
    `// PDF.js ${pdfjsPkg.version} (Apache-2.0) + page-flip (MIT) + reader-web/engine.*\n` +
    `/* eslint-disable */\n` +
    `export const READER_HTML: string = ${JSON.stringify(html)};\n`,
);
console.log(`✓ wrote ${outFile} (${(html.length / 1024 / 1024).toFixed(2)} MB, PDF.js ${pdfjsPkg.version})`);
